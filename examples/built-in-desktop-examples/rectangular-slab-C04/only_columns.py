for label, col, dp, value in COLUMNS:
    bad = 0
    for row, node in zip(DESKTOP, nodes):
        total += 1
        if round(value(node), dp) == round(row[col], dp):
            matched += 1
        else:
            bad += 1
            differed += 1
            print(f"   DIFFERS at x={row[0]:g} y={row[1]:g}: desktop {row[col]:.{dp}f}, "
                  f"script {value(node):.{dp}f}")
    desk = max(row[col] for row in DESKTOP)
    mine = max(value(node) for node in nodes)
    verdict = f"MATCH ({len(nodes)}/{len(nodes)} nodes)" if bad == 0 else f"DIFFERS at {bad} nodes"
