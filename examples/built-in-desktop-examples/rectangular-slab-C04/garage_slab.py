# The desktop and the script must be talking about the same mesh nodes
# (coordinates are printed to 2 decimals, so agree within half that digit).
assert len(nodes) == len(DESKTOP), (len(nodes), len(DESKTOP))
for row, node in zip(DESKTOP, nodes):
    assert abs(node["x"] - row[0]) <= 0.0051 and abs(node["y"] - row[1]) <= 0.0051, (row[:2], node["x"], node["y"])

# No difference from the desktop is recorded for this table, so every node
# value must match; anything else is reported as unexpected.
print(f"{'Result (every node)':24} {'Calcsheet':17} {'Desktop max':>11} {'Script max':>11}  Verdict")
print("-" * 82)
matched = differed = total = 0
for label, col, dp, value in COLUMNS:
    bad = 0
    for row, node in zip(DESKTOP, nodes):
        total += 1
        if round(value(node), dp) == round(row[col], dp):
            matched += 1
        else:
            bad += 1
            differed += 1
            print(f"   DIFFERS at x={row[0]:g} y={row[1]:g}: desktop {row[col]:.{dp}f}, "
                  f"script {value(node):.{dp}f}")
    desk = max(row[col] for row in DESKTOP)
    mine = max(value(node) for node in nodes)
    verdict = f"MATCH ({len(nodes)}/{len(nodes)} nodes)" if bad == 0 else f"DIFFERS at {bad} nodes"
    print(f"{label:24} {'ENVELOPE MAXIMUM':17} {desk:>11.{dp}f} {mine:>11.{dp}f}  {verdict}")

print("-" * 82)
print(f"{matched} of {total} results match the desktop; 0 are known differences; {differed} unexpected.")
