# ---
# Example:  Post-tensioned bridge deck on circular piers and pile caps
# Feature:  prestressed_concrete + circular_column + pile_cap + punching_shear
#           (C02 Captain + C12 Circular Column + C16 Pile Cap
#            + C23 Punching Shear)
# Repeats:  circular_column and pile_cap appear in bridge_pier_and_foundation.py
#           too; there the pier is short and the question is piles against a
#           spread base. Here the deck is post-tensioned and the question is
#           what the PT deck does to the piers.
# Verified: yes - 2026-09-02 - every number measured on prokon-automation.exe; the pier loads are C02's own
# ---
# A three-span post-tensioned deck on circular piers. The chain is the same
# as any bridge, but two things make it a script rather than a spreadsheet:
#
#   * PRESTRESS MOVES THE REACTIONS. The pier loads are not the tributary
#     load; they come out of the frame analysis with the cable forces in it.
#   * THE PIER PUNCHES INTO ITS OWN PIER HEAD, and that check needs the
#     reaction the deck actually delivers, not the one you assumed.
#
#   1. prestressed_concrete the deck: cables, losses, stresses, reactions
#   2. circular_column      each pier, from the deck's own reaction
#   3. pile_cap             each pier's cap
#   4. punching_shear       the pier head the deck sits on

import prokon.v5

# ── The brief ───────────────────────────────────────────────────────────
SPANS = (24.0, 30.0, 24.0)   # m
DECK_WIDTH = 10.5            # m of carriageway
GIRDERS = 4                  # the deck is four PT girders under a deck slab
GIRDER_WIDTH = 1.6           # m, one girder web
DECK_DEPTH = 1500.0          # mm girder depth
PIER_DIA = 1400.0            # mm
PIER_HEIGHT = 7.0            # m

# ⚠ MODEL ONE GIRDER, NOT THE WHOLE DECK. C02 analyses a beam or a strip,
# so handing it bw = 10 500 mm makes a SOLID slab 10.5 m x 1.5 m - about
# 394 kN/m of self weight, four times a real deck's. One 1.6 m girder
# carrying its share is the idealisation an engineer actually uses, and it
# keeps every number below within sight of reality.

FCU = 50.0                   # bridge concrete
FY = 500.0
FYV = 500.0
CONCRETE = 25.0

SURFACING = 2.5              # kPa
HB_UDL = 9.0                 # kPa, notional live load over the deck

print("POST-TENSIONED BRIDGE DECK ON CIRCULAR PIERS")
print(f"  spans {SPANS} m, {GIRDERS} x {GIRDER_WIDTH} m girders "
      f"{DECK_DEPTH:.0f} mm deep under a {DECK_WIDTH} m carriageway")
print(f"  piers {PIER_DIA:.0f} mm dia x {PIER_HEIGHT} m")

# One girder's share: its own strip of surfacing, deck slab and live load.
share = DECK_WIDTH / GIRDERS
deck_slab = 0.25 * CONCRETE * share                  # the 250 mm deck slab
dead_line = (SURFACING * share) + deck_slab
live_line = HB_UDL * share
print(f"  per girder: dead {dead_line:.1f} kN/m (surfacing + deck slab), "
      f"live {live_line:.1f} kN/m")
print(f"  the girder's OWN weight is generated by the engine: "
      f"{GIRDER_WIDTH * DECK_DEPTH / 1000.0 * CONCRETE:.1f} kN/m")

# ── 1. The deck ─────────────────────────────────────────────────────────
deck = prokon.v5.prestressed_concrete.analyse(
    design_code="Eurocode 2 - 2004",
    title="PT deck, 24-30-24",
    fcu=FCU, fy=FY, fyv=FYV,
    fci=FCU * 0.6,
    ec=35e6, est=200e6,
    density=CONCRETE,
    top_cover=50.0, bottom_cover=50.0,
    permanent_live_load_pct=20.0,
    creep=1.6,
    balanced_dead_load_pct=90.0,
    generated_profile="Parabolic",
    tendon_properties=[{
        "no": 1, "bond": "Bonded", "strength": 1860.0, "max_stress_pct": 75,
        "dia": 90, "area": 1400, "k": 0.0010, "u": 0.19, "pullin": 8,
        "relax": 2.5, "est": 195e6, "min_harp_radius": 6.0,
    }],
    sections=[{"name": "girder", "bw": GIRDER_WIDTH * 1000.0,
               "d": DECK_DEPTH}],
    span_segments=[{"span": n + 1, "length": length,
                    "sec_left": "girder"}
                   for n, length in enumerate(SPANS)],
    supports=[{"no": n + 1} if n in (0, len(SPANS)) else
              {"no": n + 1, "d_below": PIER_DIA, "b_below": 0,
               "h_below": PIER_HEIGHT, "code_below": "F"}
              for n in range(len(SPANS) + 1)],
    loads=[row for n, _ in enumerate(SPANS) for row in (
        {"case": "D", "span": n + 1, "wl": dead_line},
        {"case": "L", "span": n + 1, "wl": live_line},
    )],
)["result"]

print(f"\n1. DECK  (C02)   {deck['nspan']} spans, {deck['ltot']:.1f} m, "
      f"{deck['npos']} positions")
print(f"   ULS moments   {min(deck['uls']['mnu']):>10.0f} .. "
      f"{max(deck['uls']['mpu']):>9.0f} kNm")
print(f"   SLS stresses  {min(deck['sls']['svsmi']):>10.2f} .. "
      f"{max(deck['sls']['svsma']):>9.2f} MPa  "
      f"(permissible {-deck['sls']['fct'] / 1e6:.2f} .. "
      f"{deck['sls']['fcc'] / 1e6:.2f})")
print(f"   transfer      {min(deck['transfer']['svtmi']):>10.2f} .. "
      f"{max(deck['transfer']['svtma']):>9.2f} MPa  "
      f"(permissible {-deck['transfer']['fctt'] / 1e6:.2f} .. "
      f"{deck['transfer']['fcct'] / 1e6:.2f})")

worst_deflection = max(abs(value) for value in deck["deflections"]["ditot"])
print(f"   deflection    {worst_deflection:>10.1f} mm  "
      f"(span/{max(SPANS) * 1000.0 / max(worst_deflection, 1e-9):.0f})")
print(f"   cable force   {deck['cables']['pax'][0]:>10.0f} kN at x = 0")
print(f"   losses: elastic {deck['cables']['perc_elas']:.2f} % + "
      f"creep {deck['cables']['perc_creep']:.2f} % + "
      f"shrinkage {deck['cables']['perc_shrink']:.2f} % + "
      f"relaxation {deck['cables']['perc_relax']:.2f} % "
      f"+ wedge {deck['cables']['perc_wedge']:.2f} %")
print(f"   quantities: cable {deck['quantities']['cable_mass']:.0f} kg, "
      f"rebar {deck['quantities']['main_rebar_mass']:.0f} kg over "
      f"{deck['quantities']['slab_area']:.0f} m2")

# ── The pier reactions, and how to trust them ──────────────────────────
# C02 publishes no support reactions. It publishes SHEAR ENVELOPES, and the
# reaction at a support is the jump across it. Three things make that
# derivation easy to get wrong, and all three were got wrong first:
#
#   1. a support occupies TWO result positions, about 0.1 mm apart;
#   2. the shear on the two sides of a support has OPPOSITE SIGN, so the
#      jump uses the NEGATIVE envelope on the left and the POSITIVE on the
#      right - taking the positive envelope on both sides double-counts one
#      side and misses the other;
#   3. an END support has ONE position, and there the reaction is the
#      envelope pointing INTO the span, not a jump at all.
#
# ⭐ AND THERE IS A WAY TO PROVE IT RATHER THAN BELIEVE IT. C01 publishes
# reaction_ultimate directly AND publishes the same kind of shear envelope.
# So the derivation is run against C01 first, where the right answer is
# known, and only then applied to C02. That is what validate_derivation()
# below does - and it is the difference between a technique and a guess.


def reactions_from_envelope(positions, negative, positive, support_x):
    """Support reactions from a shear envelope. See the note above."""
    found = []
    for target in support_x:
        near = [index for index, x in enumerate(positions)
                if abs(x - target) < 0.002]
        if not near:
            found.append(0.0)
        elif len(near) == 1:
            # An end support: the envelope pointing into the adjacent span.
            index = near[0]
            found.append(abs(positive[index]) if index == 0
                         else abs(negative[index]))
        else:
            found.append(abs(negative[near[0]]) + abs(positive[near[-1]]))
    return found


def validate_derivation():
    """Run the derivation on C01, where the answer is published. Returns
    (published, derived, worst relative error)."""
    spans = (6.0, 8.0, 6.0)
    beam = prokon.v5.continuous_beam.analyse(
        design_code="BS8110 - 1997",
        fcu=35.0, fy=500.0, fyv=250.0,
        concrete_density=25.0,
        sections=[{"n": 1, "bw": 400.0, "d": 700.0}],
        segments=[{"span": n + 1, "length": length, "sec_left": 1}
                  for n, length in enumerate(spans)],
        supports=[{"n": n + 1} for n in range(len(spans) + 1)],
        loads=[row for n, _ in enumerate(spans) for row in (
            {"case": "Dead", "span": n + 1, "w_left": 40.0},
            {"case": "Live", "span": n + 1, "w_left": 25.0})],
    )["result"]
    published = [support["reaction_ultimate"] for support in beam["supports"]]
    walk = [0.0]
    for length in spans:
        walk.append(walk[-1] + length)
    derived = reactions_from_envelope(
        beam["envelopes"]["position"],
        beam["envelopes"]["shear_negative"],
        beam["envelopes"]["shear_positive"],
        walk)
    error = max(abs(d / p - 1.0) for p, d in zip(published, derived) if p)
    return published, derived, error


published, derived, error = validate_derivation()
print(f"\n   THE DERIVATION, VALIDATED ON C01 FIRST:")
print(f"   {'support':>8} {'C01 published':>15} {'derived':>12} {'error':>9}")
for number, (a, b) in enumerate(zip(published, derived), start=1):
    print(f"   {number:>8} {a:>15.1f} {b:>12.1f} "
          f"{100.0 * (b / a - 1.0) if a else 0.0:>8.3f} %")
print(f"   worst error {100.0 * error:.4f} %"
      f"  ->  {'the derivation is sound; now apply it to C02' if error < 0.001 else 'DO NOT TRUST IT ON C02'}")

positions = deck["positions"]
support_x = [0.0]
for length in SPANS:
    support_x.append(support_x[-1] + length)

reactions = reactions_from_envelope(
    positions, deck["uls"]["snu"], deck["uls"]["spu"], support_x)
# ⚠ INCLUDE THE SELF WEIGHT, or the check is meaningless. The engine
# generates it from `density` and the section, so it is NOT in
# dead_line - and on a 1.5 m deep girder it is the biggest load there
# is. The first version of this check omitted it and reported a ratio
# of 3.37, which looked like a broken derivation and was a broken
# CONTROL.
self_weight_line = GIRDER_WIDTH * DECK_DEPTH / 1000.0 * CONCRETE
applied = ((1.35 * (dead_line + self_weight_line) + 1.5 * live_line)
           * sum(SPANS))

print(f"\n   PIER REACTIONS from the shear envelope:")
print(f"   {'support':>8} {'x (m)':>8} {'R uls (kN)':>12}  what it is")
for number, (x, reaction) in enumerate(zip(support_x, reactions), start=1):
    kind = "abutment" if number in (1, len(support_x)) else "PIER"
    print(f"   {number:>8} {x:>8.1f} {reaction:>12.0f}  {kind}")
ratio = sum(reactions) / applied
print(f"   sum {sum(reactions):.0f} kN against {applied:.0f} kN applied")
print(f"     (1.35 x [{dead_line:.1f} superimposed + "
      f"{self_weight_line:.1f} self weight] + 1.5 x {live_line:.1f}) x "
      f"{sum(SPANS):.0f} m")
print(f"   ratio {ratio:.3f}"
      f"  ->  {'the derivation balances' if 0.85 < ratio < 1.15 else 'CHECK IT - the reactions and the load do not agree'}")

pier_reactions = reactions[1:-1]

# ── 2. The piers ────────────────────────────────────────────────────────
# A bridge pier is monolithic with the deck at the top and fixed at the
# base, so it is NOT a cantilever here: effective length ~= the height.
# Braking is shared between the piers.
BRAKING_TOTAL = 900.0        # kN over the whole deck
braking_each = BRAKING_TOTAL / len(pier_reactions)

print(f"\n2. PIERS  (C12)   {PIER_DIA:.0f} mm dia, {PIER_HEIGHT} m, "
      f"braking {braking_each:.0f} kN each")
print(f"   {'pier':>5} {'N uls':>9} {'M base':>9} {'steel':>9} {'%':>7} "
      f"{'slender':>8}  verdict")

piers = []
for number, reaction in enumerate(pier_reactions, start=2):
    base_moment = braking_each * PIER_HEIGHT / 2.0     # fixed both ends
    pier = prokon.v5.circular_column.analyse(
        design_code="Eurocode 2 - 2004",
        diameter=PIER_DIA, cover=60.0,
        fcu=FCU, fy=FY,
        lex=PIER_HEIGHT * 1000.0, ley=PIER_HEIGHT * 1000.0,
        end_cond_top_x="PartiallyFixed", end_cond_top_y="PartiallyFixed",
        end_cond_bot_x="FullyFixed", end_cond_bot_y="FullyFixed",
        bracing_x="Braced", bracing_y="Braced",
        deltas=1.0,
        load_cases=[{"n": reaction,
                     "m1x": base_moment, "m2x": base_moment * 0.5,
                     "m1y": base_moment * 0.3}],
    )["result"]
    case = pier["load_case_results"][0]
    piers.append((number, reaction, pier))
    print(f"   {number:>5} {reaction:>9.0f} {base_moment:>9.0f} "
          f"{pier['total_as']:>9.0f} {pier['percentage_steel']:>7.3f} "
          f"{str(case['slender_x']):>8}  "
          f"{'OK' if pier['all_pass'] else 'FAILS'}")

# ── 3. The pile caps ────────────────────────────────────────────────────
print(f"\n3. PILE CAPS  (C16)   one per pier")
print(f"   {'pier':>5} {'piles':>6} {'plan':>14} {'thick':>7} "
      f"{'worst SF':>9} {'tie As':>9}  verdict")

for number, reaction, pier in piers:
    answer = None
    for count in (4, 5):
        for thickness in (1.8, 2.1, 2.4):
            try:
                cap = prokon.v5.pile_cap.analyse(
                    design_code="Eurocode 2 - 2004",
                    eu_country="UnitedKingdom",
                    gamma_c=1.5, gamma_s=1.15, alpha_cc=0.85,
                    column_dim_x=PIER_DIA / 1000.0,
                    column_dim_y=0.0,             # circular pier
                    no_of_piles=count,
                    pile_dia=0.9, pile_spacing=3.0, pile_tolerance=0.075,
                    cap_thickness=thickness, cap_overhang=0.45,
                    bottom_rebar_depth=0.15,
                    fc=FCU, fy=FY,
                    load_cases=[{"name": f"Pier {number}", "load_factor": 1.0,
                                 "p": reaction,
                                 "hx": braking_each,
                                 "mx": braking_each * PIER_HEIGHT / 2.0}],
                )["result"]
            except prokon.v5.ProkonError as refusal:
                print(f"   {number:>5} {count:>6} {'-':>14} {thickness:>7.1f} "
                      f"{'-':>9} {'-':>9}  "
                      f"{refusal.message.encode('ascii', 'replace').decode()}")
                continue

            factors = (
                [(s["load_cases"][0]["sf"], f"strut {s['element_index']}")
                 for s in cap["strut_results"]]
                + [(cap["column_node"]["load_cases"][0]["sf"], "column node")]
                + [(n["load_cases"][0]["sf"], f"pile node {n['index']}")
                   for n in cap["pile_nodes"]])
            worst_factor, where = min(factors)
            by_element = {tie["element_index"]: tie
                          for tie in cap["tie_results"]}
            tie = by_element[cap["design_tie"]]["load_cases"][0]
            ok = (worst_factor >= 1.0 and not cap["has_uplift"]
                  and cap["is_stable"] and cap["geometry_is_valid"])
            print(f"   {number:>5} {count:>6} "
                  f"{cap['cap_dim_x']:>6.2f} x {cap['cap_dim_y']:<5.2f} "
                  f"{thickness:>7.1f} {worst_factor:>9.3f} "
                  f"{tie['as_required']:>9.0f}  "
                  f"{'OK (' + where + ')' if ok else 'inadequate'}")
            if ok:
                answer = cap
                break
        if answer:
            break
    if answer is None:
        print(f"   {number:>5}   nothing in the range works for this pier")

# ── 4. The pier head, punched by the deck ──────────────────────────────
# The deck bears on the pier through a head. That is a punching problem,
# and the load is the reaction C02 published - not the tributary load.
HEAD_DEPTH = 1200.0          # mm of pier head
worst_pier = max(pier_reactions)

print(f"\n4. PIER HEAD  (C23)   {PIER_DIA:.0f} mm pier into a "
      f"{HEAD_DEPTH:.0f} mm head")
print(f"   V = {worst_pier:.0f} kN, the worst pier reaction from C02")

head = prokon.v5.punching_shear.analyse(
    design_code="Eurocode 2 - 2004",
    national_annex="GB",
    col_width=PIER_DIA,
    col_breadth=0.0,             # <= 0 declares a CIRCULAR column
    effective_depth=HEAD_DEPTH - 70.0,
    # INTERNAL. An edge inside the outermost perimeter makes the engine
    # treat the column as an edge or corner column and cuts uo, so a
    # genuinely internal head needs a genuinely large distance.
    nearest_edge_x=30_000.0,
    nearest_edge_y=30_000.0,
    fcu=FCU, fy=FY, fyv=FYV,
    asx_1=6000.0, asx_2=7000.0, asx_3=8000.0, asx_4=9000.0,
    asy_1=5000.0, asy_2=6000.0, asy_3=7000.0, asy_4=8000.0,
    load_cases=[{"v": worst_pier, "mx": 250.0, "my": 120.0}],
)["result"]

face = head["vu"][head["critical_load_case_index"]]
print(f"   column-face perimeter uo = {head['uo']:.0f} mm")
print(f"   face vu {face:.4f} MPa against vcu {head['vcu']:.4f}"
      f"  ->  {'OK' if face <= head['vcu'] else 'FACE OVERSTRESSED'}")
print(f"   {'perim':>6} {'ucrit':>9} {'Vcap':>10} {'Veff':>10} {'Asv':>10}")
for perimeter in head["critical_perimeters"]:
    print(f"   {perimeter['perimeter']:>6} {perimeter['ucrit']:>9.0f} "
          f"{perimeter['vcap']:>10.0f} {perimeter['veff']:>10.0f} "
          f"{perimeter['asv']:>10.0f}")
needs = [p["perimeter"] for p in head["critical_perimeters"] if p["asv"] > 0]
print(f"   perimeters needing shear steel: {needs or 'none - the head is deep enough'}")

# ⚠ A CIRCULAR COLUMN'S PERIMETER IS WORTH CHECKING. The engine is known to
# treat a zero breadth as a SQUARE column of side col_width rather than as
# a circle, so uo comes back as 4 x col_width and not pi x col_width.
square_uo = 4.0 * PIER_DIA
circular_uo = 3.141592653589793 * PIER_DIA
print(f"   uo reads {head['uo']:.0f} mm: 4 x D is {square_uo:.0f}, "
      f"pi x D is {circular_uo:.0f}")
if abs(head["uo"] - square_uo) < 1.0:
    print("   -> it is the SQUARE perimeter. col_breadth = 0 declares a")
    print("      circular column to the wrapper, but the native engine")
    print("      computes the bounding square. That is conservative for")
    print("      punching (a bigger perimeter is not), so KNOW which one")
    print("      you have before quoting a utilisation.")

print("\n" + "-" * 72)
print("Prestress moved the reactions, and every number below the deck came")
print("from that shear envelope. Change the balanced-load percentage at the")
print("top and watch the piers and the caps follow.")
