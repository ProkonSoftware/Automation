# ---
# Example:  Span/depth ratios, and what really drives a deflection
# Feature:  continuous_beam (C01 Continuous Beam)
# Verified: yes - 2026-09-02 - the reference beam reproduces the pinned steel/deflection/crack values; every sweep row measured on prokon-automation.exe
# ---
# "Span over twenty" is the oldest rule of thumb in concrete, and it is
# usually right. This script shows WHERE it is right, and what it does not
# know about.
#
#   1. the span/depth chart - which depths pass span/250 at each span
#   2. WHAT DRIVES THE DEFLECTION - creep, shrinkage and permanent live
#      load, each moved on its own so the contribution is visible
#   3. continuity - the same beam as one span, two, three and four
#   4. what the rule of thumb misses: crack width
#
# ⚠ THE POINT OF SECTION 2 IS THAT THE ANSWER IS NOT THE ELASTIC
# DEFLECTION. On a real beam the long-term terms dominate, and they are
# driven by inputs that default to ZERO - so a beam analysed without them
# looks two to three times stiffer than it is.

import prokon.v5

CODE = "BS8110 - 1997"
WIDTH = 300.0
FCU = 30.0
FY = 450.0
FYV = 250.0
CONCRETE = 25.0

DEAD = 20.0        # kN/m applied (self weight is generated by the engine)
LIVE = 10.0        # kN/m

LONG_TERM = dict(live_permanent_percent=25.0, creep_coefficient=2.0,
                 shrinkage_strain=300e-6)


def beam(spans, depth, width=WIDTH, **overrides):
    settings = dict(
        design_code=CODE, fcu=FCU, fy=FY, fyv=FYV,
        cover_top=30.0, cover_bot=40.0,
        **LONG_TERM,
    )
    settings.update(overrides)
    return prokon.v5.continuous_beam.analyse(
        **settings,
        sections=[{"n": 1, "bw": width, "d": depth}],
        segments=[{"span": n + 1, "length": length, "sec_left": 1}
                  for n, length in enumerate(spans)],
        supports=[{"n": n + 1} for n in range(len(spans) + 1)],
        loads=[row for n, _ in enumerate(spans) for row in (
            {"case": "Dead", "span": n + 1, "w_left": DEAD},
            {"case": "Live", "span": n + 1, "w_left": LIVE})],
    )["result"]


print("SPAN / DEPTH RATIOS, AND WHAT DRIVES A DEFLECTION")
print(f"  {WIDTH:.0f} mm wide, dead {DEAD:.0f} + live {LIVE:.0f} kN/m applied")

# ── The anchor ──────────────────────────────────────────────────────────
# The pinned reference beam: two 6 m spans, 300 x 500.
PINNED = (805.0209555473922, 1235.4393480298781, 0.6078222002339925,
          12.446682698091044, 0.11738993516717798)
anchor = beam((6.0, 6.0), 500.0)
measured = (anchor["spans"][0]["max_bottom_steel"],
            anchor["spans"][0]["max_top_steel"],
            anchor["spans"][0]["max_shear_steel"],
            anchor["max_deflection"],
            anchor["max_crack_width"])
print(f"\n  anchor: 2 x 6 m, 300 x 500")
for name, value, pin in zip(("As bot", "As top", "Asv/sv", "deflection",
                             "crack width"), measured, PINNED):
    print(f"    {name:<12} {value!r:22} pinned {pin!r}")
print(f"    -> {'EXACT on all five' if measured == PINNED else 'DRIFTED'}")

# ── 1. The span/depth chart ────────────────────────────────────────────
SPANS = (5.0, 6.0, 7.0, 8.0, 9.0, 10.0, 12.0)
DEPTHS = (400.0, 500.0, 600.0, 700.0, 800.0, 900.0, 1000.0)

print(f"\n1. SHALLOWEST DEPTH THAT PASSES SPAN/250   two equal spans")
print(f"   {'span':>6} {'depth':>7} {'L/d':>6} {'defl':>8} {'limit':>8} "
      f"{'As bot':>9} {'crack':>8}")

for length in SPANS:
    limit = length * 1000.0 / 250.0
    answer = None
    for depth in DEPTHS:
        result = beam((length, length), depth)
        if result["max_deflection"] <= limit:
            answer = (depth, result)
            break
    if answer is None:
        print(f"   {length:>6.1f}   nothing up to {DEPTHS[-1]:.0f} mm passes "
              f"span/250")
        continue
    depth, result = answer
    print(f"   {length:>6.1f} {depth:>7.0f} {length * 1000.0 / depth:>6.1f} "
          f"{result['max_deflection']:>8.2f} {limit:>8.1f} "
          f"{result['spans'][0]['max_bottom_steel']:>9.0f} "
          f"{result['max_crack_width']:>8.4f}")

print("   -> the L/d column IS the rule of thumb, computed rather than")
print("      remembered. Note that it is not constant: a longer span wants")
print("      a LOWER L/d, because deflection grows faster than depth does.")

# ── 2. What drives the deflection ──────────────────────────────────────
# Start from the elastic case - every long-term input at zero - and add
# them back one at a time. This is the table that explains why a beam
# analysed "quickly" comes out far too shallow.
print(f"\n2. WHAT DRIVES THE DEFLECTION   2 x 8 m, 300 x 700")
print(f"   {'inputs':<44} {'total':>9} {'vs elastic':>11}")

PROBES = (
    ("elastic only (all long-term inputs 0)",
     dict(live_permanent_percent=0.0, creep_coefficient=0.0,
          shrinkage_strain=0.0)),
    ("+ 25 % of the live load permanent",
     dict(live_permanent_percent=25.0, creep_coefficient=0.0,
          shrinkage_strain=0.0)),
    ("+ creep 2.0",
     dict(live_permanent_percent=25.0, creep_coefficient=2.0,
          shrinkage_strain=0.0)),
    ("+ shrinkage 300 microstrain",
     dict(live_permanent_percent=25.0, creep_coefficient=2.0,
          shrinkage_strain=300e-6)),
    ("creep 3.0 instead of 2.0",
     dict(live_permanent_percent=25.0, creep_coefficient=3.0,
          shrinkage_strain=300e-6)),
    ("100 % of the live load permanent",
     dict(live_permanent_percent=100.0, creep_coefficient=2.0,
          shrinkage_strain=300e-6)),
)

elastic = None
components = {}
for label, overrides in PROBES:
    result = beam((8.0, 8.0), 700.0, **overrides)
    total = result["max_deflection"]
    if elastic is None:
        elastic = total
    components[label] = result
    print(f"   {label:<44} {total:>9.2f} {total / elastic:>10.2f}x")

# The engine also splits the deflection into its own components, which is
# the direct answer rather than an inference from the sweep.
full = components["+ shrinkage 300 microstrain"]["spans"][0]
print(f"\n   and C01's OWN breakdown, on the full case:")
print(f"     elastic          {full['max_elastic_deflection']:>8.3f} mm")
print(f"     shrinkage        {full['max_shrinkage_deflection']:>8.3f} mm")
print(f"     long term        {full['max_long_term_deflection']:>8.3f} mm")
print(f"     TOTAL            {full['max_total_deflection']:>8.3f} mm")
share = 100.0 * full["max_elastic_deflection"] / full["max_total_deflection"]
print(f"   -> the elastic term is only {share:.0f} % of the answer. The other")
print(f"      {100 - share:.0f} % comes from three inputs that are ZERO when")
print(f"      omitted: live_permanent_percent, creep_coefficient and")
print(f"      shrinkage_strain. A beam analysed without them is not")
print(f"      optimistic, it is answering a different question.")

# ── 3. Continuity ──────────────────────────────────────────────────────
print(f"\n3. CONTINUITY   8 m spans, 300 x 700, one span to four")
print(f"   {'spans':>6} {'sag':>9} {'hog':>9} {'defl':>8} {'As bot':>9} "
      f"{'As top':>9} {'vs 1 span':>10}")

single = None
for count in (1, 2, 3, 4):
    result = beam(tuple([8.0] * count), 700.0)
    if single is None:
        single = result["max_deflection"]
    print(f"   {count:>6} {result['max_sagging_moment']:>9.1f} "
          f"{result['max_hogging_moment']:>9.1f} "
          f"{result['max_deflection']:>8.2f} "
          f"{result['spans'][0]['max_bottom_steel']:>9.0f} "
          f"{result['spans'][0]['max_top_steel']:>9.0f} "
          f"{result['max_deflection'] / single:>9.2f}x")

print("   -> continuity is free stiffness. The first extra span buys most")
print("      of it; beyond three, adding spans changes very little. That is")
print("      the argument for a continuous beam over a series of simple")
print("      ones, quantified rather than asserted.")

# ── 4. What the rule of thumb does not know ────────────────────────────
# A beam can pass span/250 comfortably and still crack too wide, because
# crack width is driven by the steel STRESS and the bar arrangement, not by
# the deflection. Sweep the depth at a fixed span and watch both.
CRACK_LIMIT = 0.3       # mm, ordinary internal exposure
print(f"\n4. DEFLECTION AND CRACK WIDTH ARE DIFFERENT QUESTIONS   2 x 8 m")
print(f"   {'depth':>7} {'defl':>8} {'/limit':>8} {'crack':>8} "
      f"{'/' + str(CRACK_LIMIT):>7} {'governs':<14}")

limit = 8000.0 / 250.0
for depth in (500.0, 600.0, 700.0, 800.0, 900.0, 1000.0):
    result = beam((8.0, 8.0), depth)
    deflection_ratio = result["max_deflection"] / limit
    crack_ratio = result["max_crack_width"] / CRACK_LIMIT
    governs = ("deflection" if deflection_ratio > crack_ratio
               else "crack width")
    print(f"   {depth:>7.0f} {result['max_deflection']:>8.2f} "
          f"{deflection_ratio:>8.2f} {result['max_crack_width']:>8.4f} "
          f"{crack_ratio:>7.2f} {governs:<14}")

print("   -> on THIS beam deflection governs at every depth, so the")
print("      span/depth rule is doing the right job. That is worth")
print("      establishing rather than assuming, because it is a property")
print("      of the loading and not of the rule.")

# The load is what moves the two ratios apart. Sweep it at a fixed depth
# and watch the crack ratio catch the deflection one.
print(f"\n   the same 300 x 800 section, sweeping the LIVE load:")
print(f"   {'live':>7} {'defl':>8} {'/limit':>8} {'crack':>8} "
      f"{'/' + str(CRACK_LIMIT):>7} {'governs':<14}")

crossed = False
for live in (5.0, 10.0, 20.0, 40.0, 60.0, 80.0, 120.0):
    result = prokon.v5.continuous_beam.analyse(
        design_code=CODE, fcu=FCU, fy=FY, fyv=FYV,
        cover_top=30.0, cover_bot=40.0, **LONG_TERM,
        sections=[{"n": 1, "bw": WIDTH, "d": 800.0}],
        segments=[{"span": n + 1, "length": 8.0, "sec_left": 1}
                  for n in range(2)],
        supports=[{"n": n + 1} for n in range(3)],
        loads=[row for n in range(2) for row in (
            {"case": "Dead", "span": n + 1, "w_left": DEAD},
            {"case": "Live", "span": n + 1, "w_left": live})],
    )["result"]
    deflection_ratio = result["max_deflection"] / limit
    crack_ratio = result["max_crack_width"] / CRACK_LIMIT
    governs = ("deflection" if deflection_ratio > crack_ratio
               else "CRACK WIDTH")
    if governs.startswith("CRACK"):
        crossed = True
    print(f"   {live:>7.0f} {result['max_deflection']:>8.2f} "
          f"{deflection_ratio:>8.2f} {result['max_crack_width']:>8.4f} "
          f"{crack_ratio:>7.2f} {governs:<14}")

if crossed:
    print("   -> AND THERE IS THE CROSSOVER. Past a certain load the crack")
    print("      width is the binding check, and a span/depth rule cannot")
    print("      see it: crack width is driven by steel STRESS and bar")
    print("      arrangement, not by stiffness.")
else:
    print("   -> deflection still governs across the whole load range on")
    print("      this section. Establishing that is the point - the two")
    print("      ratios are independent and only a run tells you which one")
    print("      binds.")
